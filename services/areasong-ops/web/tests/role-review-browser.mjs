const contexts = [], errors = [], writes = [], reads = []
const btn = (page, name) => page.getByRole('button', { name, exact: true })
async function session(actor) {
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } }); contexts.push(context)
  await context.addCookies([{ name: 'review_actor', value: actor, url }])
  await context.route('**/*', route => new URL(route.request().url()).origin === url ? route.continue() : route.abort())
  const page = await context.newPage(); page.setDefaultTimeout(10000)
  page.on('pageerror', e => errors.push(e.message))
  page.on('request', req => { if (req.url().endsWith('/detail')) reads.push({ actor }); if (req.method() === 'POST') writes.push({ actor, url: req.url(), body: req.postDataJSON() }) })
  await page.goto(url); await btn(page, '访问控制').click(); await btn(page, '新增角色').waitFor()
  return page
}
async function refresh(page) { await page.getByTitle('刷新访问策略').click(); await btn(page, '读取服务端详情').first().waitFor() }
